package dhcp

import (
	"context"
	"net"
	"syscall"
)

// Listen opens UDP port 67 bound to one interface, with broadcast enabled.
// Binding to the device keeps replies on the provisioning network even when
// the default route points elsewhere, and keeps us deaf to DHCP on other
// networks. It needs CAP_NET_BIND_SERVICE and CAP_NET_RAW.
func Listen(iface string) (net.PacketConn, error) {
	lc := net.ListenConfig{Control: func(_, _ string, c syscall.RawConn) error {
		var serr error
		err := c.Control(func(fd uintptr) {
			if serr = syscall.SetsockoptInt(int(fd), syscall.SOL_SOCKET, syscall.SO_REUSEADDR, 1); serr != nil {
				return
			}
			if serr = syscall.SetsockoptInt(int(fd), syscall.SOL_SOCKET, syscall.SO_BROADCAST, 1); serr != nil {
				return
			}
			serr = syscall.SetsockoptString(int(fd), syscall.SOL_SOCKET, syscall.SO_BINDTODEVICE, iface)
		})
		if err != nil {
			return err
		}
		return serr
	}}
	return lc.ListenPacket(context.Background(), "udp4", "0.0.0.0:67")
}
